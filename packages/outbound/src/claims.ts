/**
 * 无依据断言的确定性检查（spec 4.6-02 的「无证据的句子被拦截」）。
 *
 * 为什么要有这个文件：§8.4 的事实锁定不能只写在提示词里——「不得编造数字」对模型只是一句请求，
 * 这句话走神时没人看得见。本文件把它做成**代码**：模型产出的每一个数，必须能在"这次喂给它的事实"里
 * 找到同一个数值，找不到就判无据。判据可复跑、可单测、不看模型脸色。
 *
 * 抽取与比对用的是 `@auto-cc/core` 的 `numbers.ts`——那份实现与 4.5-08 的数值守恒同源（AGENTS.md §2.2：
 * 同一逻辑出现第二次就抽公共层，而这里是"同一判据被两个包各要一遍"）。本文件只写**话术侧的策略**：
 * 支撑面由谁构成、取哪个方向、给调用方什么读数。
 *
 * 三条刻意的取舍，写清楚免得被当成"事实校验全在这里"：
 * 1. **只取 `added`，不取 `missing`**：话术不要求把每条依据都用上（那是写作选择），
 *    只要求"说出口的数都有出处"。方向反过来就会拦掉一切正常话术。
 * 2. **比的是归一后的数值，不是字面串**：量级折进数值，所以依据里的「2 万」能支撑话术里的「20000」；
 *    读数报出的也是这个键，与 4.5 的违规行同一口径，界面不需要再解释一套。
 * 3. **裸数字也算一个数**：年份、版本号、序数都在内——§8.4 把"时间"点名为锁定项，编不得。
 *    代价是模型若写「第 1 个想请教的点」而依据里没有 1，这条判据会把它回落成模板。
 *    回落是**可用的产出**（origin 如实标 template），不是失败，所以这个代价付得起。
 */
import { diffNumberMultiset } from '@auto-cc/core';

/**
 * 找出文案里**没有事实支撑**的数值（spec 4.6-02 的拦截判据）。
 *
 * 这里不查库、不认识 `kb`：话术服务不反向依赖知识库是 plan §4.6 裁定二，判据形状因此在纯函数里。
 * @param text 将要发出的文案（模型产出，或用户手改的）
 * @param supportedTexts 这次真正喂进去的事实原文（证据正文 + 岗位名 + 公司名 + 关键词 + 对方原话；空串与纯空白被忽略）
 * @returns 无支撑的数值键，按在文案里首次出现的先后、已去重；全部有支撑时为空数组
 */
export function findUnsupportedClaims(text: string, supportedTexts: readonly string[]): string[] {
  const support = supportedTexts
    .map((fact) => fact.trim())
    .filter((fact) => fact.length > 0)
    .join('\n');
  return diffNumberMultiset(support, text).added;
}
